--
-- المدقّق بيرفع بنود كتير مالهاش نفس الوزن. اللي اتعمل هنا هو اللي عليه دليل
-- من الكود نفسه، مش اللي المدقّق بيقوله وخلاص — والبنود اللي اتساب مكتوب
-- سبب سيبانها في آخر الملف، عشان اللي يقرا المدقّق بعدين ما يعيدش الشغل.
