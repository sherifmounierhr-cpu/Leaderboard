-- ==================================================================
-- 1. مسار البحث المثبّت في lb_permission_keys
-- ==================================================================
/*
 * الدالة بترجّع مصفوفة نصوص ثابتة وما بتلمسش أي جدول، فالخطر عملياً صفر —
 * بس هي `security definer` بتتنادى من جوّه دوال محروسة، وترك `search_path`
 * مفتوح في دالة زي دي عادة سيئة مش استثناء مقبول. سطر واحد يقفل الباب.
 *
 * `create or replace` بيحافظ على الصلاحيات الممنوحة، فمفيش grant محتاج يتعاد.
 */
create or replace function public.lb_permission_keys()
returns text[]
language sql
immutable
set search_path = ''
as $fn$
  select array['periods', 'deals', 'celebrate', 'messages', 'agents', 'teams',
               'reports', 'data', 'newsfeed', 'rates', 'devices', 'storage'];
$fn$;

-- ==================================================================
-- 2. فهرسان ميّتان بالولادة
-- ==================================================================
/*
 * اتعملوا في 0021 على افتراض إن البحث بالمطوّر والمشروع هيتم على الخادم.
 * هو مش كده: `useDeals` بتحمّل آخر 60 صفقة وبتفلتر في المتصفح، والاستعمال
 * الوحيد للعمودين على الخادم هو `group by` في `lb_deal_names` اللي بيقرا كل
 * الصفوف أصلاً. يعني مفيش استعلام يقدر يستفيد منهم مهما كبر الجدول.
 *
 * الدليل من شكل الاستعلامات مش من إحصاءات الاستعمال: جدول فيه 5 صفوف
 * أي فهرس فيه هيبان «غير مستعمَل».
 */
drop index if exists leaderboard.deals_developer_idx;
drop index if exists leaderboard.deals_project_idx;

-- ==================================================================
-- 3. الفهرس اللي الاستعلام الحقيقي محتاجه
-- ==================================================================
/*
 * قائمة الصفقات في الإدارة بترتّب بالتاريخ ثم بوقت الإدخال وبتاخد أول 60.
 * ده الاستعلام اللي بيتنادى مع كل فتح للتبويب ومع كل إضافة وحذف، والجدول ده
 * بالذات بيكبر مع كل صفقة. الترتيب هنا مطابق لـ `.order()` في `useDeals`.
 */
create index if not exists deals_recent_idx
  on leaderboard.deals (deal_date desc, created_at desc);

-- ==================================================================
-- 4. مفاتيح أجنبية على الجداول اللي بتكبر فعلاً
-- ==================================================================
/*
 * مفتاح أجنبي من غير فهرس بيخلّي حذف الصف الأب يمسح الجدول الابن سطر سطر.
 * المدقّق رفع 15 حالة؛ المضاف هنا خمسة بس — اللي فيها الجدول الابن بيكبر
 * بلا سقف **و** فيه مسار حذف حقيقي في الكود:
 *
 *   - حذف فريق  → deals و targets
 *   - حذف مستشار → sale_events
 *   - حذف مستخدم من تبويب «المستخدمون» → created_by في الاتنين
 */
create index if not exists deals_team_id_idx          on leaderboard.deals (team_id);
create index if not exists deals_created_by_idx       on leaderboard.deals (created_by);
create index if not exists sale_events_agent_id_idx   on leaderboard.sale_events (agent_id);
create index if not exists sale_events_created_by_idx on leaderboard.sale_events (created_by);
create index if not exists targets_team_id_idx        on leaderboard.targets (team_id);

-- ==================================================================
-- 5. توثيق المنع المقصود
-- ==================================================================
/*
 * المدقّق بيرفع «RLS مفعّل بلا سياسات» على الجداول دي. ده مقصود ومش نقص:
 * RLS بلا سياسة = ممنوع على الكل، وهو بالظبط المطلوب. الجداول دي بتتقرا
 * وتتكتب من جوّه دوال `security definer` محروسة بـ `lb_require`، والدالة
 * بتتخطّى RLS بصلاحية مالكها.
 *
 * إضافة سياسة هنا هتفتح الباب لا تقفله. التعليق بيخلّي النية مكتوبة على
 * الجدول نفسه، فتظهر في لوحة Supabase لأي حد يفتحها بعد كده.
 */
comment on table leaderboard.admins is
  'RLS مفعّل بلا سياسات = ممنوع على الكل عن قصد. القراءة والكتابة من دوال security definer محروسة فقط.';
comment on table leaderboard.user_access is
  'RLS مفعّل بلا سياسات = ممنوع على الكل عن قصد. القراءة والكتابة من دوال security definer محروسة فقط.';
comment on table leaderboard.usernames is
  'RLS مفعّل بلا سياسات = ممنوع على الكل عن قصد. الترجمة من اسم لبريد تتم في دالة الحافة بمفتاح الخدمة.';
comment on table leaderboard.demo_accounts is
  'RLS مفعّل بلا سياسات = ممنوع على الكل عن قصد. تُقرأ من lb_is_demo() وحدها.';
comment on table leaderboard.maintenance_log is
  'RLS مفعّل بلا سياسات = ممنوع على الكل عن قصد. الكتابة من دوال الإدارة، والقراءة من view لها.';

-- ---------------------------------------------------------------------------
-- بنود اتساب عن قصد
--
-- • باقي الـ10 مفاتيح الأجنبية (announcements، board_settings، devices،
--   media_files، team_leads، user_access): جداولها مسقوفة بطبيعتها — عدد
--   الشاشات، عدد الأصوات، عدد المستخدمين. فهرس عليها بيزوّد تكلفة الكتابة
--   وما بيوفرش حاجة، ومخطِّط الاستعلام مش هيستعمله أصلاً على حجم زي ده.
--
-- • `deals_agent_period_idx`: المدقّق قال «غير مستعمَل»، لكنه مستعمَل فعلاً —
--   `lb_admin_import` بتجمع `sum(amount_egp) where agent_id/year/quarter`
--   لكل مستشار في كل ربع. بيبان غير مستعمَل لأن الاستيراد ما اشتغلش من آخر
--   جمع إحصاءات، والجدول صغير. اتساب.
--
-- • «مستخدم مسجَّل يقدر ينفّذ دالة security definer»: 39 حالة، وكلها مقصودة.
--   ده تصميم اللوحة: الصلاحية بتتفرض جوّه الدالة بـ `lb_require`، مش بمنع
--   التنفيذ. سحب التنفيذ من `authenticated` هيوقف صفحة الإدارة كلها.
--
-- • «حماية كلمات المرور المسرّبة»: إعداد في لوحة Supabase مش في SQL —
--   Authentication ← Sign In / Providers ← Password. الكود عنده فحص في
--   المتصفح (`src/lib/pwnedPassword.ts`)، والمتصفح ممكن يتخطّى، فالإعداد ده
--   هو اللي بيفرضه على الخادم.
